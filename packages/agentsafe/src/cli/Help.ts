/** The commands, one line each; the reference page carries the rest. */
export function usage(version: string): string {
  return [
    `agentsafe ${version}: put an authority boundary in front of any agent or API.`,
    "",
    "Usage: agentsafe <command> [options]",
    "",
    "Gateway",
    "  init                 Write agentsafe.yaml for this directory",
    "  proxy                Run the gateway (--upstream URL, --port N, --mode shadow|enforcement)",
    "  run                  Run the gateway from agentsafe.yaml (same command, file first)",
    "  intercept            Run the transparent interceptor: observe every destination, govern the listed ones",
    "  host                 Serve many tenants' hosted gateways from a registry (--registry FILE, --port N)",
    "  connector            Connect one fixed TCP resource outbound (--gateway URL, --route ID, --target IP:port, --credential-file FILE)",
    "  tunnel               Open a TCP resource on 127.0.0.1 (--gateway URL, --route ID, --target IP:port, --credential-file FILE, --port N)",
    "  tcp-broker           Run the internal hosted TCP rendezvous broker (operator only)",
    "  status               Ask a running gateway what it is doing",
    "  doctor               Check the binary, configuration, upstream, Decionis and credentials",
    "  identity             Print which enforcement boundary this process is",
    "  test                 Show what reaches a target without the boundary and what enforcement prevents",
    "  config               Print the effective configuration and where each setting came from",
    "  login | logout       Store or remove a Decionis key for this user (--provision mints a free workspace)",
    "  version              Print the version",
    "",
    "Evidence",
    "  verify chain [file]  Verify a log's hash chains offline",
    "  verify bundle <dir>  Verify an evidence bundle offline",
    "  verify intent <path> Check Agent-Safe Intent vectors, or hash a binding, offline",
    "",
    "API profiles",
    "  profile list         Name the API intent profiles this build governs by",
    "  profile openapi <id> --server URL  Write a profile as the OpenAPI document of an AgentCore",
    "                       Gateway target whose server is this gateway ([--prefix TEMPLATE])",
    "",
    "Policy authoring",
    "  records upload <file.jsonl>  Send records for Decionis to author a policy from",
    "                       (--kind transaction|event|audit --platform NAME --from ISO --to ISO",
    "                        [--domain commerce] [--policy ID] [--total N] [--truncated] [--json])",
    "",
    "Trusted executor",
    "  serve                Run the proposal executor from the environment",
    "  probe-containment    Report whether a system of record answers the agent zone",
    "  edge usage-report    Count a month's edge decisions from a log and sign the report (--send)",
    "  edge verify-usage-report <report>  Check a usage report's signature and recount it",
    "  edge usage-key       Print the usage-report key's kid and public JWK (--register registers it)",
    "  edge replay-schema   Print the DDL for the shared Postgres replay store",
    "  cards holds-schema   Print the DDL for the shared Postgres card hold store",
    "",
    "  test [name=host:port]...  also dials each real target: does it answer without the gateway?",
    "  test --hosted        the same requests with Decionis deciding, in shadow, against your workspace",
    "",
    "Options shared by proxy, run, status, doctor and config:",
    "  --config <file>  --upstream <url>  --port <n>  --listen <host:port>",
    "  --mode <shadow|enforcement>  --failure-policy <failClosed|failOpen>",
    "  --authority <local|decionis>  --verbose  --json",
    "",
    "Precedence: flags, then environment, then the file, then defaults.",
    "",
  ].join("\n");
}
