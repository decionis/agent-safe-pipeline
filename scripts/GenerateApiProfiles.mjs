/**
 * The API intent profiles under profiles/<platform>/<api>/<version>/ are the
 * one source. This writes what is derived from them:
 *
 * - packages/pipeline/src/profile/BuiltInApiProfiles.ts, the pipeline's
 *   mirror of every profile.json, so the runtime never reads profiles/;
 * - each profile directory's MANIFEST.sha256, over every file in it.
 *
 * `--check` compares instead of writing and exits 1 on a difference; the
 * pipeline's tests read the same files on every run.
 *
 *   node scripts/GenerateApiProfiles.mjs [--check]
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const PROFILES = join(ROOT, "profiles");
const MIRROR = join(ROOT, "packages/pipeline/src/profile/BuiltInApiProfiles.ts");
/** Every version a profile.json may declare: 1, and 1.1, which admits a write's `effect`. */
const CONTRACTS = ["agent-safe.profile.api/1", "agent-safe.profile.api/1.1"];

/** Every directory under profiles/ that holds an API intent profile, in a stable order. */
function profileDirectories() {
  const found = [];
  const walk = (directory) => {
    for (const entry of readdirSync(directory).sort()) {
      const path = join(directory, entry);
      if (!statSync(path).isDirectory()) continue;
      const file = join(path, "profile.json");
      if (existsSync(file) && CONTRACTS.includes(JSON.parse(readFileSync(file, "utf8")).profile)) {
        found.push(path);
      } else {
        walk(path);
      }
    }
  };
  walk(PROFILES);
  return found;
}

function filesOf(directory) {
  const files = [];
  const walk = (current) => {
    for (const entry of readdirSync(current).sort()) {
      const path = join(current, entry);
      if (statSync(path).isDirectory()) walk(path);
      else if (entry !== "MANIFEST.sha256") files.push(path);
    }
  };
  walk(directory);
  return files.sort((a, b) => relative(directory, a).localeCompare(relative(directory, b)));
}

function manifestOf(directory) {
  return filesOf(directory)
    .map((file) => {
      const digest = createHash("sha256").update(readFileSync(file)).digest("hex");
      return `${digest}  ${relative(directory, file)}\n`;
    })
    .join("");
}

async function renderMirror(directories) {
  const profiles = directories.map((directory) =>
    JSON.parse(readFileSync(join(directory, "profile.json"), "utf8")),
  );
  const source = `// Generated by scripts/GenerateApiProfiles.mjs from profiles/**/profile.json; do not edit.
import type { ApiProfileDefinition } from "./ApiProfile.js";

/**
 * Every API intent profile this build ships, exactly as profiles/ states it.
 * The runtime never reads profiles/: the generator mirrors them here, and the
 * pipeline's tests compare this mirror with the files and their manifests on
 * every run, so a drift is a failing test rather than a silent disagreement.
 */
export const BUILT_IN_API_PROFILES: readonly ApiProfileDefinition[] = ${JSON.stringify(profiles, null, 2)};
`;
  const options = (await prettier.resolveConfig(MIRROR)) ?? {};
  return await prettier.format(source, { ...options, filepath: MIRROR });
}

const check = process.argv.includes("--check");
const directories = profileDirectories();
const outputs = [[MIRROR, await renderMirror(directories)]];
for (const directory of directories) {
  outputs.push([join(directory, "MANIFEST.sha256"), manifestOf(directory)]);
}
let stale = 0;
for (const [path, content] of outputs) {
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === content) continue;
  if (check) {
    process.stderr.write(
      `${relative(ROOT, path)} is stale; run node scripts/GenerateApiProfiles.mjs\n`,
    );
    stale += 1;
  } else {
    writeFileSync(path, content, "utf8");
    process.stdout.write(`wrote ${relative(ROOT, path)}\n`);
  }
}
if (check && stale > 0) process.exit(1);
if (check)
  process.stdout.write(`${directories.length} API profiles and their mirror are current\n`);
